export type KbTextKey = keyof typeof T;

export function kt(key: KbTextKey, lang: RLang, vars?: Record<string, string | number>): string {
  let s: string = T[key][lang === 'zh' ? 0 : 1];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
