/** 內建知識庫的固定 id 前綴。 */
export const BUILTIN_KB_PREFIX = 'kb-builtin-';

/** 某 id 是否為內建知識庫(唯讀,禁止 PUT/DELETE)。 */
export function isBuiltinKbId(id: string): boolean {
  return id.startsWith(BUILTIN_KB_PREFIX);
}

/** 產生全部內建知識庫記錄(以程式碼為真相源,不落 S3)。 */
export function builtinKnowledgeBases(): KnowledgeBaseRecord[] {
  return BUILTIN_DEFS.map((d) => ({
    id: `${BUILTIN_KB_PREFIX}${d.genre}`,
    name: d.name,
    description: d.description,
    kind: 'category' as const,
    genre: d.genre,
    markdown: d.markdown,
    builtin: true,
    // 版本與報告規格來自同 genre 的 GenreProfile(知識庫 = Agent 知識 + 報告規格)。
    ...(getGenreProfile(d.genre) ? { version: getGenreProfile(d.genre)!.version } : {}),
    ...(describeProfile(d.genre) ? { reportProfile: describeProfile(d.genre) } : {}),
    createdAt: BUILTIN_TS,
  }));
}

/** 依 id 取單一內建知識庫(不存在回 null)。 */
export function getBuiltinKnowledgeBase(id: string): KnowledgeBaseRecord | null {
  return builtinKnowledgeBases().find((r) => r.id === id) ?? null;
}

/**
 * 依 app genre 回傳對應的內建知識庫 id(該 genre 有內建才回,否則 null)。
 * 供任務提交時自動掛上「依類型」的領域知識,驅動探索/測試更懂這款遊戲。
 */
export function genreBuiltinKbId(genre: string | undefined): string | null {
  if (!genre) return null;
  const id = `${BUILTIN_KB_PREFIX}${genre}`;
  return BUILTIN_DEFS.some((d) => d.genre === genre) ? id : null;
}

